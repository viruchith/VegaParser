"""Scale and concurrency guarantees for `init`.

- Parallel and sequential runs produce byte-identical output.
- A parser shared across threads gives the same results as sequential parsing.
- Submission to the thread pool is bounded.
- A file that fails to parse makes `init` exit 2, is reported, and is retried next run.
"""

from __future__ import annotations

import json
import shutil
import threading
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict
from pathlib import Path

import pytest
from typer.testing import CliRunner

from repo_parser import cli as cli_module
from repo_parser.cache import cache_path
from repo_parser.cli import MAX_INFLIGHT_PER_WORKER, app
from repo_parser.parser.engine import ParserEngine

CORPUS = Path(__file__).parent.parent / "eval_corpus"
FIXTURES = Path(__file__).parent.parent / "fixtures"
runner = CliRunner()


@pytest.fixture()
def in_tmp(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    return tmp_path


def _copy(src: Path, dest: Path) -> Path:
    shutil.copytree(src, dest)
    return dest


def _generated(root: Path) -> dict[str, bytes]:
    """Generated bytes with the absolute root replaced, since each run uses its own temp dir."""
    kb = root / ".rag_kb"

    def norm(data: bytes) -> bytes:
        for form in {str(root), root.as_posix()}:
            data = data.replace(form.encode(), b"<ROOT>")
        return data

    out = {f"modules/{p.name}": norm(p.read_bytes()) for p in (kb / "modules").glob("*.md")}
    out["project_index.md"] = norm((kb / "project_index.md").read_bytes())
    out["parse_cache.json"] = norm(cache_path(root).read_bytes())
    return out


def _init(root: Path, workers: int):
    return runner.invoke(app, ["init", str(root), "--log-target", "console", "-j", str(workers)])


@pytest.mark.parametrize("corpus", ["python_app", "typescript_app", "java_app"])
def test_parallel_and_sequential_output_is_byte_identical(in_tmp, corpus):
    # Same basename under two parents: the project name comes from the directory name.
    seq = _copy(CORPUS / corpus, in_tmp / "seq" / "repo")
    par = _copy(CORPUS / corpus, in_tmp / "par" / "repo")

    assert _init(seq, workers=1).exit_code == 0
    assert _init(par, workers=8).exit_code == 0

    assert _generated(seq) == _generated(par)


def test_fixtures_parallel_and_sequential_output_is_byte_identical(in_tmp):
    seq = _copy(FIXTURES, in_tmp / "seq" / "repo")
    par = _copy(FIXTURES, in_tmp / "par" / "repo")
    assert _init(seq, workers=1).exit_code == 0
    assert _init(par, workers=8).exit_code == 0
    assert _generated(seq) == _generated(par)


def test_shared_engine_is_safe_across_threads(in_tmp):
    """One ParserEngine parsing the same files from many threads matches sequential results."""
    files = sorted(p for p in (CORPUS / "python_app").rglob("*.py")) + sorted(
        p for p in (CORPUS / "typescript_app").rglob("*.ts")
    )
    jobs = [(p.relative_to(CORPUS).as_posix(), p.read_text(encoding="utf-8")) for p in files] * 4

    engine = ParserEngine()
    baseline = {rel: engine.parse_file(rel, src) for rel, src in jobs}

    shared = ParserEngine()

    def work(job):
        rel, src = job
        return rel, shared.parse_file(rel, src)

    with ThreadPoolExecutor(max_workers=8) as pool:
        results = list(pool.map(work, jobs))

    for rel, parsed in results:
        assert asdict(parsed) == asdict(baseline[rel]), rel


def test_threads_have_independent_parsers():
    """Each worker thread gets its own parser object. A shared one is not thread-safe.

    The parsers are kept alive until the assertion. Recording only ``id()`` and
    then letting the thread exit frees a thread-local parser, and CPython can
    reuse that address for the next thread.
    """
    engine = ParserEngine()
    seen: dict[str, object] = {}
    lock = threading.Lock()

    def grab():
        parser = engine._get_parser("python")
        with lock:
            seen[threading.current_thread().name] = parser

    threads = [threading.Thread(target=grab, name=f"t{i}") for i in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert all(parser is not None for parser in seen.values())
    assert len({id(parser) for parser in seen.values()}) == len(seen)


def test_submission_is_bounded(in_tmp, monkeypatch):
    """No more than workers * MAX_INFLIGHT_PER_WORKER futures are outstanding at once."""
    repo = _copy(CORPUS / "python_app", in_tmp / "repo")
    workers = 2
    limit = workers * MAX_INFLIGHT_PER_WORKER

    state = {"outstanding": 0, "peak": 0}
    lock = threading.Lock()

    class CountingPool(ThreadPoolExecutor):
        def submit(self, fn, /, *args, **kwargs):
            with lock:
                state["outstanding"] += 1
                state["peak"] = max(state["peak"], state["outstanding"])
            future = super().submit(fn, *args, **kwargs)

            def _done(_future):
                with lock:
                    state["outstanding"] -= 1

            future.add_done_callback(_done)
            return future

    monkeypatch.setattr(cli_module, "ThreadPoolExecutor", CountingPool)
    result = _init(repo, workers=workers)
    assert result.exit_code == 0, result.output
    assert 0 < state["peak"] <= limit


def test_failed_parse_exits_2_reports_file_and_keeps_knowledge_base(in_tmp, monkeypatch):
    repo = _copy(CORPUS / "python_app", in_tmp / "repo")
    original = ParserEngine.parse_file

    def failing_for_orders(self, filepath, source):
        if filepath.endswith("services/orders.py"):
            return None
        return original(self, filepath, source)

    monkeypatch.setattr(ParserEngine, "parse_file", failing_for_orders)
    result = _init(repo, workers=1)

    assert result.exit_code == 2, result.output
    assert "Failed on 1 file(s)" in result.output
    assert "services/orders.py" in result.output
    assert (repo / ".rag_kb" / "project_index.md").is_file()
    assert list((repo / ".rag_kb" / "modules").glob("*.md"))


def test_failed_file_is_not_cached_and_is_retried(in_tmp, monkeypatch):
    repo = _copy(CORPUS / "python_app", in_tmp / "repo")
    original = ParserEngine.parse_file
    monkeypatch.setattr(
        ParserEngine,
        "parse_file",
        lambda self, fp, src: None if fp.endswith("services/orders.py") else original(self, fp, src),
    )
    assert _init(repo, workers=1).exit_code == 2

    payload = json.loads(cache_path(repo).read_text(encoding="utf-8"))
    assert "app/services/orders.py" not in payload["files"]

    monkeypatch.setattr(ParserEngine, "parse_file", original)
    assert _init(repo, workers=1).exit_code == 0
